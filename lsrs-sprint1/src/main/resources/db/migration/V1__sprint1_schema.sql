CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_no VARCHAR(12) UNIQUE,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('STUDENT','ADMIN')),
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING','ACTIVE')),
    no_show_count INTEGER NOT NULL DEFAULT 0 CHECK (no_show_count >= 0),
    restricted_until TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE email_verification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id),
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    consumed_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_verification_user ON email_verification(user_id, created_at);
CREATE TABLE seat (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(8) NOT NULL UNIQUE,
    zone VARCHAR(24) NOT NULL,
    qr_token_hash VARCHAR(64) NOT NULL UNIQUE
);
CREATE TABLE policy_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no BIGINT NOT NULL UNIQUE,
    mode VARCHAR(20) NOT NULL CHECK (mode IN ('NORMAL','EXAM')),
    normal_max_minutes INTEGER NOT NULL CHECK (normal_max_minutes > 0),
    exam_max_minutes INTEGER NOT NULL CHECK (exam_max_minutes > 0),
    grace_minutes INTEGER NOT NULL CHECK (grace_minutes > 0),
    reservation_unit_minutes INTEGER NOT NULL CHECK (reservation_unit_minutes > 0),
    no_show_threshold INTEGER NOT NULL CHECK (no_show_threshold > 0),
    restriction_days INTEGER NOT NULL CHECK (restriction_days > 0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE reservation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id),
    seat_id BIGINT NOT NULL REFERENCES seat(id),
    policy_version_id BIGINT NOT NULL REFERENCES policy_version(id),
    start_at TIMESTAMP WITH TIME ZONE NOT NULL,
    end_at TIMESTAMP WITH TIME ZONE NOT NULL,
    reserved_at TIMESTAMP WITH TIME ZONE NOT NULL,
    check_in_deadline_at TIMESTAMP WITH TIME ZONE NOT NULL,
    checked_in_at TIMESTAMP WITH TIME ZONE,
    completed_at TIMESTAMP WITH TIME ZONE,
    status VARCHAR(24) NOT NULL CHECK (status IN ('RESERVED','CHECKED_IN','COMPLETED','AUTO_CANCELLED')),
    CHECK (start_at < end_at)
);
CREATE INDEX idx_reservation_seat_range ON reservation(seat_id, status, start_at, end_at);
CREATE INDEX idx_reservation_user_range ON reservation(user_id, status, start_at, end_at);
